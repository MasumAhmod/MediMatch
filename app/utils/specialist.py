# =========================================================
# GET SPECIALIZATION
# =========================================================

def get_specialization(
    disease: str
) -> str:
    """
    Return the recommended medical specialization
    for a predicted disease.
    """

    if not disease:
        return "General Medicine"

    disease = disease.strip().lower()

    return DISEASE_SPECIALIZATION.get(
        disease,
        "General Medicine"
    )


